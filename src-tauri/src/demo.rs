//! Bundled demo fixture lookup and the static, clearly-labelled example analyses.
use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use tauri::{AppHandle, Manager, path::BaseDirectory};
use wotslog_core::AppError;
use wotslog_core::types::{Diagnosis, ErrorGroup, Evidence};

const ANALYSES: &str = include_str!("../../fixtures/demo_analysis.json");

pub fn demo_path(app: &AppHandle) -> Result<PathBuf, AppError> {
    let bundled = app
        .path()
        .resolve("fixtures/demo.log", BaseDirectory::Resource)
        .ok();
    if let Some(p) = bundled.filter(|p| p.is_file()) {
        return Ok(p);
    }
    // `tauri dev` fallback: fixed path inside the repository (never user-supplied).
    let dev = PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../fixtures/demo.log"));
    if cfg!(debug_assertions) && dev.is_file() {
        return Ok(dev);
    }
    Err(AppError::FileNotFound)
}

#[derive(Deserialize)]
struct Entry {
    r#match: String,
    diagnosis: RawDiagnosis,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct RawDiagnosis {
    summary: String,
    likely_causes: Vec<String>,
    evidence: Vec<RawEvidence>,
    next_steps: Vec<String>,
    uncertainty: String,
}

#[derive(Deserialize)]
struct RawEvidence {
    sample: usize,
    explanation: String,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DemoAnalysis {
    pub is_demo: bool,
    pub label: &'static str,
    pub diagnosis: Diagnosis,
}

/// Static example for a demo-log group; evidence line numbers come from the group's real sample lines.
pub fn example_for(group: &ErrorGroup) -> Result<DemoAnalysis, AppError> {
    let entries: Vec<Entry> =
        serde_json::from_str(ANALYSES).map_err(|e| AppError::Io(e.to_string()))?;
    let e = entries
        .into_iter()
        .find(|e| group.signature.contains(&e.r#match))
        .ok_or_else(|| {
            AppError::InvalidArgument("no example analysis exists for this group".into())
        })?;
    let d = e.diagnosis;
    Ok(DemoAnalysis {
        is_demo: true,
        label: "DEMO: static example analysis, not generated by an AI model from your data.",
        diagnosis: Diagnosis {
            summary: d.summary,
            likely_causes: d.likely_causes,
            evidence: d
                .evidence
                .into_iter()
                .filter_map(|ev| {
                    group
                        .sample_line_numbers
                        .get(ev.sample)
                        .map(|&line_number| Evidence {
                            line_number,
                            explanation: ev.explanation,
                        })
                })
                .collect(),
            next_steps: d.next_steps,
            uncertainty: d.uncertainty,
        },
    })
}
