// Browser-preview backend used ONLY when the app runs outside Tauri (e.g. the hosted web demo).
// It serves precomputed synthetic demo data; no files are read and nothing is sent anywhere.
import type {
  AiSettingsView, DemoAnalysis, ErrorGroup, LogEntry, PageResult, ScanResult, SessionInfo,
} from '@/types'

interface Raw extends LogEntry { raw: string }
interface Data {
  session: SessionInfo
  summary: ScanResult
  entries: Raw[]
  analyses: { match: string; diagnosis: { summary: string; likelyCauses: string[]; evidence: { sample: number; explanation: string }[]; nextSteps: string[]; uncertainty: string } }[]
}

export const isTauri = () => typeof window !== 'undefined' && '__TAURI_INTERNALS__' in window

let cache: Promise<Data> | null = null
const data = () => (cache ??= fetch(`${import.meta.env.BASE_URL}web-demo.json`).then((r) => r.json() as Promise<Data>))
const err = (code: string, message: string) => ({ code, message })

export const webBackend = {
  selectLog: async (): Promise<SessionInfo | null> => {
    throw err('webDemo', 'Opening your own files needs the desktop app. This browser preview only includes the synthetic demo log.')
  },
  loadDemo: async () => (await data()).session,
  scanLog: async (): Promise<ScanResult> => (await data()).summary,
  queryLogs: async (a: { sessionId: string; query: string; severity: string | null; offset: number; limit: number; scanId: string }): Promise<PageResult> => {
    const d = await data()
    const q = a.query.toLowerCase()
    const m = d.entries.filter((e) => (!a.severity || e.severity === a.severity) && (!q || e.raw.toLowerCase().includes(q)))
    return {
      sessionId: a.sessionId, scanId: a.scanId, totalMatches: m.length, offset: a.offset, limit: a.limit,
      entries: m.slice(a.offset, a.offset + a.limit).map(({ raw: _raw, ...e }) => e),
    }
  },
  prepareAnalysis: async (): Promise<never> => {
    throw err('aiDisabled', 'Live AI is not available in the browser preview.')
  },
  demoAnalysis: async (_s: string, groupId: string): Promise<DemoAnalysis> => {
    const d = await data()
    const g: ErrorGroup | undefined = d.summary.topErrors.find((x) => x.id === groupId)
    const e = g && d.analyses.find((x) => g.signature.includes(x.match))
    if (!g || !e) throw err('invalidArgument', 'No example analysis exists for this group.')
    return {
      isDemo: true,
      label: 'DEMO: static example analysis, not generated by an AI model from your data.',
      diagnosis: {
        ...e.diagnosis,
        evidence: e.diagnosis.evidence.flatMap((ev) => (g.sampleLineNumbers[ev.sample] ? [{ lineNumber: g.sampleLineNumbers[ev.sample], explanation: ev.explanation }] : [])),
      },
    }
  },
  getAiSettings: async (): Promise<AiSettingsView> => ({
    baseUrl: '', model: '', hasKey: false, configured: false, credentialStoreOk: true, liveAiAvailable: false,
    liveAiReason: 'Browser preview: live AI exists only in the desktop app.',
  }),
  saveAiSettings: async (): Promise<AiSettingsView> => {
    throw err('webDemo', 'Provider settings are only available in the desktop app.')
  },
}
